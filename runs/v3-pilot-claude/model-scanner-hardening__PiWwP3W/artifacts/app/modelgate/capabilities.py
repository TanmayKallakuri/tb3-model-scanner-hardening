"""Curated capability tables for Python callables (policy section 3).

Every entry is a dotted path as a pickle could name it.  ``devtools/build_kb.py``
resolves each path to the canonical identity of the object it names (so
``os.system``, ``posix.system`` and ``shutil.os.system`` are one entry) and
stores the result in ``kb_data.json``; the scanner never imports a module an
artifact names.

A capability is attached to the *call* of the callable.  Values are either a
kind, or ``(kind, condition)`` where the condition narrows when the call
exercises the capability:

* ``("truthy", index, keyword)``: only when that argument is given and true
  (``ftplib.FTP(host)`` connects, ``ftplib.FTP()`` does not).
* ``("notnone", index, keyword)``: only when that argument is not None.
* ``("path", index, keyword)``: only when that argument names a file (a str,
  bytes or path object) rather than an in-memory file object.
* ``("kw", keyword)``: only when that keyword argument is given and true.
* ``("notmemory", index, keyword)``: sqlite3 databases other than ``:memory:``.

Paths that do not exist in this interpreter (other platforms, removed modules,
packages that are not installed) are kept under their written name.

Callables whose only side effect is incidental and not steerable by the
artifact (``tempfile.gettempdir`` probing /tmp, ``platform.platform`` running
``uname -p``, ``ctypes.util.find_library`` running ``ldconfig``) are deliberately
absent: they give an attacker nothing and are natural "harmless" calls.
"""

